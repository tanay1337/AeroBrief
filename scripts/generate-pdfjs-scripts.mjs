import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const pdf = readFileSync(resolve(root, 'node_modules/pdfjs-dist/build/pdf.min.js'), 'utf8');
const worker = readFileSync(resolve(root, 'node_modules/pdfjs-dist/build/pdf.worker.min.js'), 'utf8');
const output = `/* Generated by scripts/generate-pdfjs-scripts.mjs. Do not edit manually. */\n` +
  `export const PDFJS_SOURCE = ${JSON.stringify(pdf)};\n` +
  `export const PDFJS_WORKER_SOURCE = ${JSON.stringify(worker)};\n`;

writeFileSync(resolve(root, 'src/vendor/pdfjsScripts.generated.ts'), output);
console.log('Generated local PDF.js viewer scripts.');
