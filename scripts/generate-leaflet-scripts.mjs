import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const script = readFileSync(resolve(root, 'node_modules/leaflet/dist/leaflet.js'), 'utf8');
const styles = readFileSync(resolve(root, 'node_modules/leaflet/dist/leaflet.css'), 'utf8');
const output = `/* Generated by scripts/generate-leaflet-scripts.mjs. Do not edit manually. */\n` +
  `export const LEAFLET_SOURCE = ${JSON.stringify(script)};\n` +
  `export const LEAFLET_STYLES = ${JSON.stringify(styles)};\n`;

writeFileSync(resolve(root, 'src/vendor/leafletScripts.generated.ts'), output);
console.log('Generated local Leaflet map scripts.');
